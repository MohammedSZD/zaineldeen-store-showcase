export const products = catalog.map((p) => {
  const brand = p.brand ? brands[p.brand] : null;
  if (p.brand && !brand) throw new Error(`Brand missing from src/data/brands.js: ${p.brand}`);
  return { ...p, brandId: brand?.id ?? null, ar: arText[p.id] };
});

export const productById = Object.fromEntries(products.map((p) => [p.id, p]));
